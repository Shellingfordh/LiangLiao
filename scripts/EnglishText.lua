EnglishText.Catalog = EXACT

local rules = {}
local literals = {}
local function escape(s)
    return (s:gsub("([%^%$%(%)%%%.%[%]%*%+%-%?])", "%%%1"))
end
for old, new in pairs(EXACT) do
    if old ~= "" then
        if old:find("{", 1, true) or old:find("%s", 1, true) or old:find("%d", 1, true) then
            local tokens = {}
            local pattern = ""
            local cursor = 1
            while cursor <= #old do
                local a, b = old:find("{[%w_]+}", cursor)
                local c, d = old:find("%%[sd]", cursor)
                if c and (not a or c < a) then a, b = c, d end
                if not a then pattern = pattern .. escape(old:sub(cursor)); break end
                pattern = pattern .. escape(old:sub(cursor, a - 1)) .. "(.-)"
                tokens[#tokens + 1] = old:sub(a, b)
                cursor = b + 1
            end
            rules[#rules + 1] = { old = old, pattern = pattern, text = new, tokens = tokens }
        else
            literals[#literals + 1] = { old = old, text = new }
        end
    end
end
local function longest(a, b)
    if #a.old == #b.old then return a.old < b.old end
    return #a.old > #b.old
end
table.sort(rules, longest)
table.sort(literals, longest)

local function translate(text, depth)
    if EXACT[text] then return EXACT[text] end
    local out = text
    -- Whole known sentences must be consumed before generic punctuation templates.
    for _, item in ipairs(literals) do
        if #item.old > 3 then
            out = out:gsub(escape(item.old), function() return item.text end)
        end
    end
    if depth < 4 then
        for _, rule in ipairs(rules) do
            out = out:gsub(rule.pattern, function(...)
                local args = {...}
                local values = {}
                for i, token in ipairs(rule.tokens) do
                    values[token] = translate(args[i] or "", depth + 1)
                end
                local index = 0
                local result = rule.text:gsub("{[%w_]+}", function(token)
                    return values[token] or token
                end)
                result = result:gsub("%%[sd]", function()
                    index = index + 1
                    return translate(args[index] or "", depth + 1)
                end)
                return result
            end)
        end
    end
    for _, item in ipairs(literals) do
        out = out:gsub(escape(item.old), function() return item.text end)
    end
    out = out:gsub("，", ", "):gsub("。", ". "):gsub("：", ": ")
        :gsub("（", " ("):gsub("）", ")"):gsub("？", "? "):gsub("、", ", ")
    return out
end

---@overload fun(text: string): string
---@param text string?
---@return string?
function EnglishText.Translate(text)
    if type(text) ~= "string" or not text:find("[\228-\233][\128-\191][\128-\191]") then return text end
    -- Quoted player wording is content, not a game label. Preserve it byte for byte.
    local quotes = {}
    local protected = text:gsub("「(.-)」", function(value)
        quotes[#quotes + 1] = value
        return "「@@QUOTE" .. tostring(#quotes) .. "@@」"
    end)
    local out = translate(protected, 0)
    out = out:gsub("「(@@QUOTE%d+@@)」", "%1")
    out = out:gsub("@@QUOTE(%d+)@@", function(index)
        return "\"" .. quotes[tonumber(index)] .. "\" "
    end)
    return out
end

return EnglishText
